const pick = (words: string[], random: () => number) => words[Math.floor(random() * words.length)];

/** A name for a new project: today's date, and two words picked at random, such as "2026-10-21 quiet heron". */
export function newProjectName(date = new Date(), random = Math.random): string {
  const day = [date.getFullYear(), date.getMonth() + 1, date.getDate()]
    .map((part) => String(part).padStart(2, '0'))
    .join('-');
  return `${day} ${pick(ADJECTIVES, random)} ${pick(NOUNS, random)}`;
}
